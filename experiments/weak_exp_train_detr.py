def save_weak_model(model: nn.Module, path: Union[str, Path]):
    """
    Save backbone-only checkpoint for old eval compatibility and save the full
    DETR decoder checkpoint next to it.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    m = _unwrap_module(model)

    if isinstance(m, WeakMSAGOWithDETRDecoder):
        torch.save(m.backbone.state_dict(), path)
        payload = {
            "checkpoint_type": "weak_detr_decoder_v3",
            "backbone": m.backbone.state_dict(),
            "query_decoder": m.query_decoder.state_dict(),
            "num_classes": m.num_classes,
            "query_decoder_topk": m.topk,
            "query_decoder_classifier_weight_shape": tuple(m.classifier.weight.shape),
            "detr_version": 3,
        }
        full_path = path.parent / path.name.replace("weak_backbone", "weak_detr_decoder")
        torch.save(payload, full_path)

        # Alias for scripts that still look for weak_query_decoder naming.  A new
        # eval loader still needs to instantiate the V3 decoder architecture.
        alias_path = path.parent / path.name.replace("weak_backbone", "weak_query_decoder")
        torch.save(payload, alias_path)
    else:
        torch.save(m.state_dict(), path)


def _optional_float(value, default: float) -> float:
    if value is None:
        return float(default)
    try:
        v = float(value)
    except Exception:
        return float(default)
    if v <= 0:
        return float(default)
    return v


def _needs_detr_param_groups(args: argparse.Namespace) -> bool:
    names = [
        "query_embed_lr",
        "selector_lr",
        "query_decoder_lr",
        "query_embed_weight_decay",
        "selector_weight_decay",
        "query_decoder_weight_decay",
    ]
    return any(getattr(args, n, None) is not None for n in names)


def build_optimizer(model: nn.Module, args: argparse.Namespace):
    opt_name = str(args.optim).lower()

    # V3 uses AdamW param groups so that query embeddings and selector can use
    # smaller LR than the backbone.  This is safer than pushing all newly added
    # modules with the full backbone LR.
    if _needs_detr_param_groups(args) or bool(getattr(args, "use_query_decoder", False)):
        base_lr = float(args.lr)
        qdec_lr = _optional_float(getattr(args, "query_decoder_lr", None), base_lr)
        qemb_lr = _optional_float(getattr(args, "query_embed_lr", None), base_lr)
        sel_lr = _optional_float(getattr(args, "selector_lr", None), base_lr)

        base_wd = float(args.weight_decay)
        qdec_wd = _optional_float(getattr(args, "query_decoder_weight_decay", None), base_wd)
        qemb_wd = _optional_float(getattr(args, "query_embed_weight_decay", None), base_wd)
        sel_wd = _optional_float(getattr(args, "selector_weight_decay", None), base_wd)

        groups: Dict[Tuple[str, bool], dict] = {}

        def group_spec(name: str):
            n = name.replace("module.", "")
            if "query_decoder.query_embedder.go_embedding" in n:
                cat, lr, wd = "query_embed", qemb_lr, qemb_wd
            elif "query_decoder.selector" in n:
                cat, lr, wd = "selector", sel_lr, sel_wd
            elif "query_decoder" in n:
                cat, lr, wd = "query_decoder", qdec_lr, qdec_wd
            else:
                cat, lr, wd = "backbone", base_lr, base_wd
            return cat, lr, wd

        for name, p in model.named_parameters():
            if not p.requires_grad:
                continue
            cat, lr, wd = group_spec(name)
            no_decay = bool(args.no_model_weight_decay) and (p.ndim <= 1 or name.endswith(".bias"))
            effective_wd = 0.0 if no_decay else wd
            key = (cat, no_decay)
            if key not in groups:
                groups[key] = {
                    "params": [],
                    "lr": lr,
                    "weight_decay": effective_wd,
                    "name": f"{cat}_{'no_decay' if no_decay else 'decay'}",
                }
            groups[key]["params"].append(p)

        param_groups = [g for g in groups.values() if g["params"]]
        return torch.optim.AdamW(param_groups, eps=float(args.optim_eps))

    # Fallback path preserved for non-DETR use.
    no_weight_decay = set()
    if hasattr(model, "no_weight_decay"):
        try:
            no_weight_decay = set(model.no_weight_decay())
        except Exception:
            no_weight_decay = set()

    if opt_name == "lamb":
        try:
            from timm.optim import create_optimizer_v2
            return create_optimizer_v2(
                model,
                opt="lamb",
                lr=float(args.lr),
                weight_decay=float(args.weight_decay),
                eps=float(args.optim_eps),
                filter_bias_and_bn=bool(args.no_model_weight_decay),
            )
        except Exception as e:
            rank0_print(f"[Optimizer] Lamb unavailable, fallback AdamW. Reason: {repr(e)}")

    if bool(args.no_model_weight_decay):
        decay, no_decay = [], []
        for name, p in model.named_parameters():
            if not p.requires_grad:
                continue
            if p.ndim <= 1 or name.endswith(".bias") or name in no_weight_decay:
                no_decay.append(p)
            else:
                decay.append(p)
        return torch.optim.AdamW(
            [
                {"params": decay, "weight_decay": float(args.weight_decay)},
                {"params": no_decay, "weight_decay": 0.0},
            ],
            lr=float(args.lr),
            eps=float(args.optim_eps),
        )

    return torch.optim.AdamW(
        model.parameters(),
        lr=float(args.lr),
        weight_decay=float(args.weight_decay),
        eps=float(args.optim_eps),
    )


def build_scheduler(optimizer, args, total_steps: int):
    policy = str(args.lr_policy).lower()
    max_lr = [float(g.get("lr", args.lr)) for g in optimizer.param_groups]
    if policy in {"onecycle", "cycle"}:
        return torch.optim.lr_scheduler.OneCycleLR(
            optimizer,
            max_lr=max_lr,
            total_steps=max(1, int(total_steps)),
            pct_start=float(args.lr_pct_start),
            three_phase=bool(args.lr_cycle_three_phase),
            div_factor=float(args.lr_div_factor),
            final_div_factor=float(args.lr_final_div_factor),
            anneal_strategy="cos",
        )
    if policy == "cosine":
        return torch.optim.lr_scheduler.CosineAnnealingLR(
            optimizer,
            T_max=max(1, int(total_steps)),
            eta_min=float(args.min_lr),
        )
    raise ValueError(f"Unknown lr_policy: {args.lr_policy}")


def wrap_ddp(model: nn.Module, args: argparse.Namespace, device: torch.device):
    if not getattr(args, "distributed", False):
        return model
    from torch.nn.parallel import DistributedDataParallel as DDP
    if device.type == "cuda":
        return DDP(
            model,
            device_ids=[args.local_rank],
            output_device=args.local_rank,
            find_unused_parameters=bool(args.ddp_find_unused_parameters),
        )
    return DDP(model, find_unused_parameters=bool(args.ddp_find_unused_parameters))


