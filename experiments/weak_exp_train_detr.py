_PROB_EPS = 1e-6


def _unwrap_module(m: nn.Module) -> nn.Module:
    return m.module if hasattr(m, "module") else m


def prob_to_logit(prob: torch.Tensor, eps: float = _PROB_EPS) -> torch.Tensor:
    prob = prob.float().clamp(eps, 1.0 - eps)
    return torch.log(prob) - torch.log1p(-prob)


def safe_gather_2d(x: torch.Tensor, idx: torch.Tensor) -> torch.Tensor:
    """x: [B, C], idx: [B, K] -> [B, K]."""
    return torch.gather(x, dim=1, index=idx)


def build_backbone_memory(
    h: torch.Tensor,
    mode: str = "tokens_plus_pooled",
    memory_grid_h: int = 0,
    memory_grid_w: int = 0,
):
    """
    Convert backbone feature to decoder memory.

    Returns
    -------
    memory_tokens: [B, T, C]
    pooled:        [B, C]
    """
    if h.ndim == 4:
        if memory_grid_h > 0 and memory_grid_w > 0:
            h = F.adaptive_avg_pool2d(h, (memory_grid_h, memory_grid_w))

        pooled = F.adaptive_avg_pool2d(h, 1).flatten(1)
        tokens = h.flatten(2).transpose(1, 2).contiguous()

        if mode == "pooled":
            memory = pooled.unsqueeze(1)
        elif mode == "tokens":
            memory = tokens
        elif mode == "tokens_plus_pooled":
            memory = torch.cat([pooled.unsqueeze(1), tokens], dim=1)
        else:
            raise ValueError(f"Unknown memory mode: {mode}")
        return memory, pooled

    if h.ndim == 3:
        memory = h
        pooled = h.mean(dim=1)
        return memory, pooled

    if h.ndim == 2:
        pooled = h
        return h.unsqueeze(1), pooled

    pooled = h.flatten(1)
    return pooled.unsqueeze(1), pooled


def find_classifier_linear(arch_model: nn.Module, num_classes: int) -> nn.Linear:
    """
    Find the final classifier linear layer in Arch/rnet.
    This layer's weight is used as the classifier semantic anchor for GO terms.
    """
    m = _unwrap_module(arch_model)
    candidates: List[nn.Linear] = []

    if hasattr(m, "get_fc"):
        try:
            fc = m.get_fc()
            if isinstance(fc, nn.Linear) and fc.out_features == int(num_classes):
                return fc
            for sub in fc.modules():
                if isinstance(sub, nn.Linear) and sub.out_features == int(num_classes):
                    candidates.append(sub)
        except Exception:
            pass

    for sub in m.modules():
        if isinstance(sub, nn.Linear) and sub.out_features == int(num_classes):
            candidates.append(sub)

    if not candidates:
        raise RuntimeError(
            f"Cannot find classifier nn.Linear with out_features={num_classes}. "
            "The DETR ontology decoder requires classifier weights as GO anchors."
        )

    return candidates[-1]

def summarize_delta_gate(qout: dict, device: torch.device) -> Dict[str, torch.Tensor]:
    gate = qout.get("delta_gate", None)
    if gate is None:
        z = torch.tensor(0.0, device=device)
        return {
            "delta_gate_mean": z,
            "delta_gate_p50": z,
            "delta_gate_p95": z,
        }

    g = gate.detach().float().flatten()
    if g.numel() == 0:
        z = torch.tensor(0.0, device=device)
        return {
            "delta_gate_mean": z,
            "delta_gate_p50": z,
            "delta_gate_p95": z,
        }

    return {
        "delta_gate_mean": g.mean(),
        "delta_gate_p50": torch.quantile(g, 0.50),
        "delta_gate_p95": torch.quantile(g, 0.95),
    }

class LightweightCandidateSelector(nn.Module):
    """
    Two-stage candidate selector.

    Stage 1: fixed prefilter by base/external/blend score.
    Stage 2: learnable reranker over top-M candidates.

    Because top-k is discrete, this module must be trained with an explicit
    selector auxiliary loss on prefilter candidates.  Without that loss, the
    selector is mostly a non-trainable routing heuristic.
    """

    def __init__(
        self,
        num_classes: int,
        topk: int,
        use_learnable_selector: bool = True,
        prefilter_topm: int = 1024,
        static_source: str = "blend",
        external_prob_blend_alpha: float = 1.0,
        hidden_dim: int = 64,
        dropout: float = 0.1,
        use_term_bias: bool = True,
        selector_logit_residual_scale: float = 1.0,
        use_protein_term_affinity: bool = True,
        detach_term_features: bool = True,
        include_label_boost: bool = False,
        label_boost: float = 2.0,
    ):
        super().__init__()
        self.num_classes = int(num_classes)
        self.topk = int(topk)
        self.use_learnable_selector = bool(use_learnable_selector)
        self.prefilter_topm = int(max(prefilter_topm, topk))
        self.static_source = str(static_source)
        self.external_prob_blend_alpha = float(external_prob_blend_alpha)
        self.selector_logit_residual_scale = float(selector_logit_residual_scale)
        self.use_protein_term_affinity = bool(use_protein_term_affinity)
        self.detach_term_features = bool(detach_term_features)
        self.include_label_boost = bool(include_label_boost)
        self.label_boost = float(label_boost)

        # base_logit, base_prob, external_prob, external_logit,
        # static_score, has_external, protein_term_affinity
        self.feature_dim = 7 if self.use_protein_term_affinity else 6

        if self.use_learnable_selector:
            self.score_mlp = nn.Sequential(
                nn.LayerNorm(self.feature_dim),
                nn.Linear(self.feature_dim, hidden_dim),
                nn.GELU(),
                nn.Dropout(dropout),
                nn.Linear(hidden_dim, 1),
            )
            # Start as close as possible to the static selector.
            nn.init.zeros_(self.score_mlp[-1].weight)
            nn.init.zeros_(self.score_mlp[-1].bias)

            if use_term_bias:
                self.term_bias = nn.Embedding(num_classes, 1)
                nn.init.zeros_(self.term_bias.weight)
            else:
                self.term_bias = None
        else:
            self.score_mlp = None
            self.term_bias = None

    @staticmethod
    def _canonical_source(source: str) -> str:
        source = str(source).lower()
        aliases = {
            "base_topk": "base",
            "external": "prob",
            "external_topk": "prob",
            "prob_topk": "prob",
            "mixed": "blend",
            "blend_topk": "blend",
        }
        return aliases.get(source, source)

    def _external_or_base(
        self,
        base_prob: torch.Tensor,
        external_prob: Optional[torch.Tensor],
        has_external_prob: Optional[torch.Tensor],
    ) -> torch.Tensor:
        if external_prob is None:
            return base_prob
        ext = external_prob.float().clamp(0.0, 1.0)
        if has_external_prob is not None:
            hp = has_external_prob.bool().view(-1, 1)
            ext = torch.where(hp, ext, base_prob)
        return ext

    def _make_static_score(
        self,
        base_logits: torch.Tensor,
        external_prob: Optional[torch.Tensor] = None,
        has_external_prob: Optional[torch.Tensor] = None,
        source: Optional[str] = None,
        alpha: Optional[float] = None,
        y_hint: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        source = self._canonical_source(source or self.static_source)
        alpha = self.external_prob_blend_alpha if alpha is None else float(alpha)

        base_prob = torch.sigmoid(base_logits.float())
        ext_prob = self._external_or_base(base_prob, external_prob, has_external_prob)

        if source == "base":
            score = base_prob
        elif source == "prob":
            score = ext_prob
        elif source == "blend":
            score = alpha * ext_prob + (1.0 - alpha) * base_prob
        elif source == "external_or_base":
            score = ext_prob
        else:
            raise ValueError(f"Unknown query_decoder_topk_source: {source}")

        # Kept only for ablation; off by default to avoid train/eval mismatch.
        if self.include_label_boost and y_hint is not None:
            score = score + y_hint.float() * self.label_boost
        return score

    def _protein_term_affinity(
        self,
        prefilter_idx: torch.Tensor,
        pooled_feature: Optional[torch.Tensor],
        classifier_weight: Optional[torch.Tensor],
    ) -> torch.Tensor:
        if pooled_feature is None or classifier_weight is None:
            return torch.zeros(prefilter_idx.shape, device=prefilter_idx.device, dtype=torch.float32)
        if pooled_feature.shape[-1] != classifier_weight.shape[-1]:
            return torch.zeros(prefilter_idx.shape, device=prefilter_idx.device, dtype=torch.float32)

        cw = classifier_weight.detach() if self.detach_term_features else classifier_weight
        pf = pooled_feature.detach() if self.detach_term_features else pooled_feature
        term_w = F.embedding(prefilter_idx, cw)  # [B, M, D]
        pf = pf.float().unsqueeze(1)             # [B, 1, D]
        aff = F.cosine_similarity(term_w.float(), pf, dim=-1)
        return aff.clamp(-1.0, 1.0)

    def forward(
        self,
        base_logits: torch.Tensor,
        external_prob: Optional[torch.Tensor] = None,
        has_external_prob: Optional[torch.Tensor] = None,
        topk_source: Optional[str] = None,
        external_prob_blend_alpha: Optional[float] = None,
        y_hint: Optional[torch.Tensor] = None,
        pooled_feature: Optional[torch.Tensor] = None,
        classifier_weight: Optional[torch.Tensor] = None,
    ) -> dict:
        B, C = base_logits.shape
        K = min(self.topk, C)

        static_score = self._make_static_score(
            base_logits=base_logits,
            external_prob=external_prob,
            has_external_prob=has_external_prob,
            source=topk_source,
            alpha=external_prob_blend_alpha,
            y_hint=y_hint,
        )

        if not self.use_learnable_selector:
            topk_score, topk_idx = torch.topk(static_score, k=K, dim=1)
            return {
                "topk_idx": topk_idx,
                "topk_score": topk_score,
                "prefilter_idx": topk_idx,
                "prefilter_score": topk_score,
                "selector_logits": None,
            }

        M = min(max(self.prefilter_topm, K), C)
        prefilter_score, prefilter_idx = torch.topk(static_score, k=M, dim=1)

        base_logit_sel = safe_gather_2d(base_logits.float(), prefilter_idx)
        base_prob_sel = torch.sigmoid(base_logit_sel)

        if external_prob is not None:
            ext_full = external_prob.float().clamp(0.0, 1.0)
            ext_prob_sel = safe_gather_2d(ext_full, prefilter_idx)
            if has_external_prob is not None:
                hp_sel = has_external_prob.bool().view(-1, 1).expand_as(ext_prob_sel)
                ext_prob_sel = torch.where(hp_sel, ext_prob_sel, base_prob_sel)
                has_external_sel = hp_sel.float()
            else:
                has_external_sel = torch.ones_like(ext_prob_sel)
            ext_logit_sel = prob_to_logit(ext_prob_sel)
        else:
            ext_prob_sel = torch.zeros_like(base_prob_sel)
            ext_logit_sel = torch.zeros_like(base_prob_sel)
            has_external_sel = torch.zeros_like(base_prob_sel)

        static_prob_sel = prefilter_score.float().clamp(0.0, 1.0)

        features = [
            base_logit_sel,
            base_prob_sel,
            ext_prob_sel,
            ext_logit_sel,
            static_prob_sel,
            has_external_sel,
        ]

        if self.use_protein_term_affinity:
            aff = self._protein_term_affinity(prefilter_idx, pooled_feature, classifier_weight)
            features.append(aff)

        feat = torch.stack(features, dim=-1)  # [B, M, F]
        residual = self.score_mlp(feat).squeeze(-1)

        if self.term_bias is not None:
            residual = residual + self.term_bias(prefilter_idx).squeeze(-1)

        static_logit = prob_to_logit(static_prob_sel)
        selector_logits = static_logit + self.selector_logit_residual_scale * torch.tanh(residual)
        rerank_score = torch.sigmoid(selector_logits)

        local_score, local_idx = torch.topk(rerank_score, k=K, dim=1)
        topk_idx = torch.gather(prefilter_idx, dim=1, index=local_idx)
        topk_score = torch.gather(rerank_score, dim=1, index=local_idx)

        return {
            "topk_idx": topk_idx,
            "topk_score": topk_score,
            "prefilter_idx": prefilter_idx,
            "prefilter_score": prefilter_score,
            "selector_logits": selector_logits,
        }


class TrainableOntologyQueryEmbedding(nn.Module):
    """
    Query embedding for selected GO terms.

    Default V3 behavior:
        query_raw = classifier_weight[topk_idx]
                  + query_embed_residual_scale * trainable_go_residual[topk_idx]
                  + query_score_embed_scale * score_feature_projection(...)
    """

    def __init__(
        self,
        num_classes: int,
        classifier_dim: int,
        query_dim: int,
        use_trainable_query_embedding: bool = True,
        query_embed_init: str = "classifier_plus_residual",
        query_embed_residual_scale: float = 0.1,
        detach_classifier_query_weight: bool = True,
        use_query_score_features: bool = True,
        query_score_embed_scale: float = 0.1,
        query_score_detach: bool = True,
        dropout: float = 0.1,
    ):
        super().__init__()
        self.num_classes = int(num_classes)
        self.classifier_dim = int(classifier_dim)
        self.query_dim = int(query_dim)
        self.use_trainable_query_embedding = bool(use_trainable_query_embedding)
        self.query_embed_init = str(query_embed_init)
        self.query_embed_residual_scale = float(query_embed_residual_scale)
        self.detach_classifier_query_weight = bool(detach_classifier_query_weight)
        self.use_query_score_features = bool(use_query_score_features)
        self.query_score_embed_scale = float(query_score_embed_scale)
        self.query_score_detach = bool(query_score_detach)

        if self.use_trainable_query_embedding:
            self.go_embedding = nn.Embedding(num_classes, classifier_dim)
            if self.query_embed_init == "classifier_plus_residual":
                nn.init.zeros_(self.go_embedding.weight)
            elif self.query_embed_init in {"classifier_weight", "random"}:
                nn.init.normal_(self.go_embedding.weight, mean=0.0, std=0.02)
            else:
                raise ValueError(f"Unknown query_embed_init: {self.query_embed_init}")
        else:
            self.go_embedding = None

        # base_prob, external_prob, topk_score, has_external
        self.score_feature_dim = 4
        if self.use_query_score_features:
            self.score_proj = nn.Sequential(
                nn.LayerNorm(self.score_feature_dim),
                nn.Linear(self.score_feature_dim, classifier_dim),
                nn.GELU(),
                nn.Linear(classifier_dim, classifier_dim),
            )
            # Preserve the classifier anchor at initialization.
            nn.init.zeros_(self.score_proj[-1].weight)
            nn.init.zeros_(self.score_proj[-1].bias)
        else:
            self.score_proj = None

        self.out_proj = nn.Sequential(
            nn.LayerNorm(classifier_dim),
            nn.Dropout(dropout),
            nn.Linear(classifier_dim, query_dim),
        )

    @torch.no_grad()
    def reset_from_classifier_weight(self, classifier_weight: torch.Tensor) -> None:
        if not self.use_trainable_query_embedding:
            return
        if self.query_embed_init != "classifier_weight":
            return
        if classifier_weight.shape != self.go_embedding.weight.shape:
            raise ValueError(
                f"classifier_weight shape {tuple(classifier_weight.shape)} does not match "
                f"go_embedding shape {tuple(self.go_embedding.weight.shape)}"
            )
        self.go_embedding.weight.copy_(classifier_weight.detach())

    def forward(
        self,
        topk_idx: torch.Tensor,
        classifier_weight: torch.Tensor,
        base_logits: torch.Tensor,
        external_prob: Optional[torch.Tensor] = None,
        has_external_prob: Optional[torch.Tensor] = None,
        topk_score: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        if self.query_score_detach:
            base_logits_for_score = base_logits.detach()
            external_prob_for_score = None if external_prob is None else external_prob.detach()
        else:
            base_logits_for_score = base_logits
            external_prob_for_score = external_prob

        cls_weight = classifier_weight.detach() if self.detach_classifier_query_weight else classifier_weight
        cls_query = F.embedding(topk_idx, cls_weight)

        if not self.use_trainable_query_embedding:
            raw_query = cls_query
        else:
            learned = self.go_embedding(topk_idx)
            if self.query_embed_init == "random":
                raw_query = learned
            elif self.query_embed_init == "classifier_weight":
                raw_query = learned
            elif self.query_embed_init == "classifier_plus_residual":
                raw_query = cls_query + self.query_embed_residual_scale * learned
            else:
                raise ValueError(f"Unknown query_embed_init: {self.query_embed_init}")

        if self.use_query_score_features:
            base_prob_sel = torch.sigmoid(safe_gather_2d(base_logits_for_score.float(), topk_idx))

            if external_prob_for_score is not None:
                ext_prob_sel = safe_gather_2d(external_prob_for_score.float().clamp(0.0, 1.0), topk_idx)
                if has_external_prob is not None:
                    hp_sel = has_external_prob.bool().view(-1, 1).expand_as(ext_prob_sel)
                    ext_prob_sel = torch.where(hp_sel, ext_prob_sel, torch.zeros_like(ext_prob_sel))
                    has_external_sel = hp_sel.float()
                else:
                    has_external_sel = torch.ones_like(ext_prob_sel)
            else:
                ext_prob_sel = torch.zeros_like(base_prob_sel)
                has_external_sel = torch.zeros_like(base_prob_sel)

            if topk_score is None:
                topk_score = base_prob_sel

            score_feat = torch.stack(
                [
                    base_prob_sel,
                    ext_prob_sel,
                    topk_score.float().clamp(0.0, 1.0),
                    has_external_sel,
                ],
                dim=-1,
            )
            raw_query = raw_query + self.query_score_embed_scale * self.score_proj(score_feat)

        return self.out_proj(raw_query)


class ExpertGuidedOntologyQueryDecoder(nn.Module):
    """
    V3 ontology query decoder.

    The stable default is residual refinement:
        final_logits = base_logits + scatter_add(delta, topk_idx)
    """

    def __init__(
        self,
        num_classes: int,
        classifier_dim: int,
        memory_dim: int,
        query_dim: int = 256,
        num_heads: int = 8,
        num_layers: int = 1,
        ffn_dim: int = 1024,
        dropout: float = 0.1,
        delta_max: float = 0.5,
        topk: int = 100,
        mode: str = "residual",
        memory_mode: str = "tokens_plus_pooled",
        memory_grid_h: int = 0,
        memory_grid_w: int = 0,
        detach_classifier_query_weight: bool = True,
        use_trainable_query_embedding: bool = True,
        query_embed_init: str = "classifier_plus_residual",
        query_embed_residual_scale: float = 0.1,
        use_query_score_features: bool = True,
        query_score_embed_scale: float = 0.1,
        query_score_detach: bool = True,
        # query anchor
        query_decoder_logit_base_mode: str = "base_residual",
        expert_base_mix_alpha: float = 0.8,
        anchor_delta_gate_init: float = 0.1,

        use_learnable_selector: bool = True,
        selector_prefilter_topm: int = 1024,
        selector_static_source: str = "blend",
        external_prob_blend_alpha: float = 1.0,
        selector_hidden_dim: int = 64,
        selector_logit_residual_scale: float = 1.0,
        selector_use_term_bias: bool = True,
        selector_use_protein_term_affinity: bool = True,
        selector_detach_base_logits: bool = True,
        selector_detach_term_features: bool = True,
        include_label_boost: bool = False,
        label_boost: float = 2.0,
    ):
        super().__init__()
        self.num_classes = int(num_classes)
        self.classifier_dim = int(classifier_dim)
        self.memory_dim = int(memory_dim)
        self.query_dim = int(query_dim)
        self.delta_max = float(delta_max)
        self.topk = int(topk)
        self.mode = str(mode)
        self.memory_mode = str(memory_mode)
        self.memory_grid_h = int(memory_grid_h)
        self.memory_grid_w = int(memory_grid_w)
        self.selector_detach_base_logits = bool(selector_detach_base_logits)

        # query anchor
        self.query_decoder_logit_base_mode = str(query_decoder_logit_base_mode)
        self.expert_base_mix_alpha = float(expert_base_mix_alpha)

        self.delta_gate_head = nn.Sequential(
            nn.LayerNorm(query_dim),
            nn.Linear(query_dim, 1),
        )
        
        # gate controls residual magnitude. Start small to preserve anchor.
        g0 = float(anchor_delta_gate_init)
        g0 = min(max(g0, 1e-4), 1.0 - 1e-4)
        gate_bias = math.log(g0 / (1.0 - g0))
        
        last_gate = self.delta_gate_head[-1]
        nn.init.zeros_(last_gate.weight)
        nn.init.constant_(last_gate.bias, gate_bias)

        if self.mode not in {"residual", "replace"}:
            raise ValueError(f"Unknown query decoder mode: {self.mode}")

        self.selector = LightweightCandidateSelector(
            num_classes=num_classes,
            topk=topk,
            use_learnable_selector=use_learnable_selector,
            prefilter_topm=selector_prefilter_topm,
            static_source=selector_static_source,
            external_prob_blend_alpha=external_prob_blend_alpha,
            hidden_dim=selector_hidden_dim,
            dropout=dropout,
            use_term_bias=selector_use_term_bias,
            selector_logit_residual_scale=selector_logit_residual_scale,
            use_protein_term_affinity=selector_use_protein_term_affinity,
            detach_term_features=selector_detach_term_features,
            include_label_boost=include_label_boost,
            label_boost=label_boost,
        )

        self.query_embedder = TrainableOntologyQueryEmbedding(
            num_classes=num_classes,
            classifier_dim=classifier_dim,
            query_dim=query_dim,
            use_trainable_query_embedding=use_trainable_query_embedding,
            query_embed_init=query_embed_init,
            query_embed_residual_scale=query_embed_residual_scale,
            detach_classifier_query_weight=detach_classifier_query_weight,
            use_query_score_features=use_query_score_features,
            query_score_embed_scale=query_score_embed_scale,
            query_score_detach=query_score_detach,
            dropout=dropout,
        )

        self.memory_proj = nn.Sequential(
            nn.LayerNorm(memory_dim),
            nn.Linear(memory_dim, query_dim),
        )

        layer = nn.TransformerDecoderLayer(
            d_model=query_dim,
            nhead=num_heads,
            dim_feedforward=ffn_dim,
            dropout=dropout,
            activation="gelu",
            batch_first=True,
            norm_first=True,
        )
        self.decoder = nn.TransformerDecoder(decoder_layer=layer, num_layers=num_layers)
        self.delta_head = nn.Sequential(nn.LayerNorm(query_dim), nn.Linear(query_dim, 1))

        # Critical: residual decoder initially does nothing.
        nn.init.zeros_(self.delta_head[-1].weight)
        nn.init.zeros_(self.delta_head[-1].bias)

    @torch.no_grad()
    def reset_query_embedding_from_classifier_weight(self, classifier_weight: torch.Tensor) -> None:
        self.query_embedder.reset_from_classifier_weight(classifier_weight)

    def forward(
        self,
        h: torch.Tensor,
        base_logits: torch.Tensor,
        classifier_weight: torch.Tensor,
        external_prob: Optional[torch.Tensor] = None,
        has_external_prob: Optional[torch.Tensor] = None,
        topk_source: Optional[str] = None,
        external_prob_blend_alpha: Optional[float] = None,
        y_hint: Optional[torch.Tensor] = None,
    ) -> dict:
        memory_tokens, pooled_feature = build_backbone_memory(
            h,
            mode=self.memory_mode,
            memory_grid_h=self.memory_grid_h,
            memory_grid_w=self.memory_grid_w,
        )

        base_for_selector = base_logits.detach() if self.selector_detach_base_logits else base_logits

        selector_out = self.selector(
            base_logits=base_for_selector,
            external_prob=external_prob,
            has_external_prob=has_external_prob,
            topk_source=topk_source,
            external_prob_blend_alpha=external_prob_blend_alpha,
            y_hint=y_hint,
            pooled_feature=pooled_feature,
            classifier_weight=classifier_weight,
        )
        topk_idx = selector_out["topk_idx"]
        topk_score = selector_out["topk_score"]

        query = self.query_embedder(
            topk_idx=topk_idx,
            classifier_weight=classifier_weight,
            base_logits=base_logits,
            external_prob=external_prob,
            has_external_prob=has_external_prob,
            topk_score=topk_score,
        )

        memory = self.memory_proj(memory_tokens)
        decoded = self.decoder(tgt=query, memory=memory)
        raw_delta = self.delta_head(decoded).squeeze(-1)

        if self.delta_max is not None and self.delta_max > 0:
            delta = self.delta_max * torch.tanh(raw_delta)
        else:
            delta = raw_delta

        selected_logits = None

        if self.mode == "residual":
            anchor_logits, anchor_prob = build_anchor_logits_from_prob(
                base_logits=base_logits,
                external_prob=external_prob,
                has_external_prob=has_external_prob,
                mode=self.query_decoder_logit_base_mode,
                mix_alpha=self.expert_base_mix_alpha,
            )
            
            if self.query_decoder_logit_base_mode == "base_residual":
                refined_logits = base_logits.float().clone()
                refined_logits.scatter_add_(
                    dim=1,
                    index=topk_idx,
                    src=delta,
                )
            
                delta_gate = torch.ones_like(delta)
                selected_anchor_logits = torch.gather(base_logits.float(), 1, topk_idx)
            
            else:
                # Strong-anchor mode:
                #   final = anchor + gated residual on selected top-k.
                refined_logits = anchor_logits.float().clone()
            
                selected_anchor_logits = torch.gather(anchor_logits.float(), 1, topk_idx)
            
                raw_delta_gate = self.delta_gate_head(decoded).squeeze(-1)
                delta_gate = torch.sigmoid(raw_delta_gate)
            
                selected_logits = selected_anchor_logits + delta_gate * delta
            
                refined_logits.scatter_(
                    dim=1,
                    index=topk_idx,
                    src=selected_logits,
                )
        else:
            # Not recommended. Kept only as an ablation-compatible mode.
            refined_logits = base_logits.clone()
            refined_logits.scatter_(dim=1, index=topk_idx, src=delta)

        return {
            "logits": refined_logits,
            "base_logits": base_logits,
            "topk_idx": topk_idx,
            "delta": delta,
            "memory_tokens": memory_tokens,
            "pooled_feature": pooled_feature,
            "topk_score": topk_score,
            "prefilter_idx": selector_out.get("prefilter_idx"),
            "prefilter_score": selector_out.get("prefilter_score"),
            "selector_logits": selector_out.get("selector_logits"),
            "anchor_logits": anchor_logits,
            "anchor_prob": anchor_prob,
            "selected_anchor_logits": selected_anchor_logits,
            "selected_logits": selected_logits if self.query_decoder_logit_base_mode != "base_residual" else None,
            "delta_gate": delta_gate,
            "query_decoder_logit_base_mode": self.query_decoder_logit_base_mode,
        }


