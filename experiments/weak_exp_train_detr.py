def topk_positive_coverage(topk_idx: Optional[torch.Tensor], y: torch.Tensor) -> torch.Tensor:
    if topk_idx is None:
        return torch.tensor(0.0, device=y.device)
    pos = y > 0.5
    if pos.sum() == 0:
        return torch.tensor(0.0, device=y.device)
    hit = torch.gather(pos, dim=1, index=topk_idx).float().sum()
    total = pos.float().sum().clamp_min(1.0)
    return hit / total


def summarize_delta(delta: Optional[torch.Tensor], device: torch.device) -> Dict[str, torch.Tensor]:
    if delta is None:
        z = torch.tensor(0.0, device=device)
        return {
            "delta_mean": z,
            "delta_abs_mean": z,
            "delta_abs_max": z,
            "delta_abs_p95": z,
        }
    d = delta.detach().float()
    abs_d = d.abs()
    if abs_d.numel() == 0:
        p95 = torch.tensor(0.0, device=device)
    else:
        p95 = torch.quantile(abs_d.flatten(), 0.95)
    return {
        "delta_mean": d.mean(),
        "delta_abs_mean": abs_d.mean(),
        "delta_abs_max": abs_d.max(),
        "delta_abs_p95": p95,
    }


def compute_delta_l2_loss(qout: dict, device: torch.device) -> torch.Tensor:
    delta = qout.get("delta", None)
    if delta is None:
        return torch.tensor(0.0, device=device)
    return delta.float().pow(2).mean()


def compute_selector_aux_loss(
    qout: dict,
    target: torch.Tensor,
    target_mask: Optional[torch.Tensor] = None,
    conf: Optional[torch.Tensor] = None,
    pos_weight: float = 10.0,
) -> torch.Tensor:
    selector_logits = qout.get("selector_logits", None)
    prefilter_idx = qout.get("prefilter_idx", None)
    if selector_logits is None or prefilter_idx is None:
        return torch.tensor(0.0, device=target.device)

    target = target.float().clamp(0.0, 1.0)
    target_sel = safe_gather_2d(target, prefilter_idx)

    if target_mask is None:
        mask_sel = torch.ones_like(target_sel)
    else:
        mask_sel = safe_gather_2d(target_mask.float(), prefilter_idx)

    if conf is None:
        conf_sel = torch.ones_like(target_sel)
    else:
        conf_sel = safe_gather_2d(conf.float(), prefilter_idx)

    raw = F.binary_cross_entropy_with_logits(
        selector_logits.float(),
        target_sel.float(),
        reduction="none",
    )
    weight = mask_sel * conf_sel * (1.0 + float(pos_weight) * target_sel)
    return (raw * weight).sum() / weight.sum().clamp_min(1.0)


def compute_external_kd_loss(
    logits_u: torch.Tensor,
    prob_u: Optional[torch.Tensor],
    args: argparse.Namespace,
) -> torch.Tensor:
    """
    Optional full/logit-top-k BCE distillation to external probabilities.
    Default lambda is 0; keep this off in the first diagnostic run unless you
    intentionally want expert distillation in addition to pseudo supervision.
    """
    if prob_u is None:
        return torch.tensor(0.0, device=logits_u.device)
    kd_topk = int(getattr(args, "external_kd_topk", 0))
    p = prob_u.float().clamp(0.0, 1.0)
    if kd_topk > 0:
        k = min(kd_topk, p.shape[1])
        idx = torch.topk(p, k=k, dim=1).indices
        logits_sel = safe_gather_2d(logits_u.float(), idx)
        p_sel = safe_gather_2d(p, idx)
        return F.binary_cross_entropy_with_logits(logits_sel, p_sel, reduction="mean")
    return F.binary_cross_entropy_with_logits(logits_u.float(), p, reduction="mean")


